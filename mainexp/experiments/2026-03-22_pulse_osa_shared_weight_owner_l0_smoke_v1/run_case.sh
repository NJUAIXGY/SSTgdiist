#!/usr/bin/env bash
set -euo pipefail

CASE_ID="${1:-}"
if [ -z "$CASE_ID" ]; then
  echo "usage: $0 <pulse_osa_shared_weight_owner_l0_baseline|pulse_osa_shared_weight_owner_l0_actual>" >&2
  exit 2
fi

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
PROJECT_ROOT=$(cd "$SCRIPT_DIR/../../.." && pwd)
RUNNER="$PROJECT_ROOT/sst_dram_si/tools/run_mesh_with_time.sh"

COMMON_ENV=(
  SST_BIN=/home/xgy/remote/sst_install_mpi/bin/sst
  MESH_EXPERIMENTAL_ENABLE=1
  MESH_VALIDATE_PROFILE=paper
  MESH_MAX_STEPS=1
  MESH_STEP_SEED_ONLY_MODE=1
  MESH_STEP_ACTIVATION_FRACTION=0.03
  MESH_MEM_BACKEND=ramulator2
  MESH_RAMULATOR2_CONFIG_FILE=/home/xgy/remote/sst_dram_si/configs/ramulator2_ddr5.cfg
  MESH_SYNAPSE_WEIGHT_MODE=gcss_idx2_rowmphf
  MESH_GCSS2_DIR=/home/xgy/remote/sst_dram_si/weights/gcss_valueonly_dstcore_idx2_rowmphf_fanout256_10k_v2_j32
  MESH_GAS_VLF_ENABLE=1
  MESH_GAS_VLF_RUN_ENABLE=0
  MESH_NOC_TYPE=multicast_mesh
  MESH_MULTICAST_ENABLE=1
  MESH_MULTICAST_BLOCK_W=2
  MESH_MULTICAST_BLOCK_H=2
  MESH_MULTICAST_INGRESS_POLICY=top_left
  MESH_MULTICAST_INTER_POLICY=xy
  MESH_MULTICAST_INTRA_POLICY=manhattan_x_first
  MESH_LOCAL_STORAGE_ENABLE=1
  MESH_SRAM_MODEL_ENABLE=1
  MESH_SRAM_WEIGHT_IDX_ENABLE=1
  MESH_SRAM_WEIGHT_L0_ENABLE=1
  MESH_SRAM_WEIGHT_IDX_CAPACITY_BYTES=1048576
  MESH_SRAM_WEIGHT_L0_CAPACITY_BYTES=4194304
  MESH_SRAM_WEIGHT_IDX_BANKS=8
  MESH_SRAM_WEIGHT_L0_BANKS=8
  MESH_SRAM_WEIGHT_PORTS_PER_BANK=1
  MESH_PULSE_OSA_ENABLE=1
  MESH_PULSE_OSA_SHARED_WEIGHT_OWNER_ENABLE=1
  MESH_EXPERIMENTAL_IDX2_INGRESS_PREFETCH_ENABLE=1
  MESH_EXPERIMENTAL_IDX2_INGRESS_PREFETCH_BUDGET_PER_TICK=8
  MESH_EXPERIMENTAL_IDX2_INGRESS_PREFETCH_CACHE_ENTRIES=4096
  MESH_EXPERIMENTAL_IDX2_INGRESS_PREFETCH_GATHER_ONLY=1
  MESH_EXPERIMENTAL_IDX2_INGRESS_TAIL_GUARD_ENABLE=1
  MESH_EXPERIMENTAL_IDX2_INGRESS_BUDGET_ADAPT_ENABLE=1
  MESH_EXPERIMENTAL_IDX2_INGRESS_BUDGET_ADAPT_MAX_PER_TICK=24
  MESH_EXPERIMENTAL_IDX2_INGRESS_BUDGET_ADAPT_Q_DEPTH=16
)

case "$CASE_ID" in
  pulse_osa_shared_weight_owner_l0_baseline)
    CASE_ENV=(
      MESH_PULSE_OSA_SHARED_WEIGHT_OWNER_ACTUAL_ENABLE=0
    )
    ;;
  pulse_osa_shared_weight_owner_l0_actual)
    CASE_ENV=(
      MESH_PULSE_OSA_SHARED_WEIGHT_OWNER_ACTUAL_ENABLE=1
    )
    ;;
  *)
    echo "unknown case: $CASE_ID" >&2
    exit 2
    ;;
esac

RUN_ROOT="$SCRIPT_DIR/runs/$CASE_ID"
mkdir -p "$RUN_ROOT"

env "${COMMON_ENV[@]}" "${CASE_ENV[@]}" MESH_RUN_ROOT="$RUN_ROOT" "$RUNNER"

LATEST_RUN=$(find "$RUN_ROOT" -mindepth 1 -maxdepth 1 -type d | LC_ALL=C sort | tail -n 1)
if [ -n "${LATEST_RUN:-}" ]; then
  ln -sfn "$LATEST_RUN" "$RUN_ROOT/latest"
  echo "[run_case] latest -> $LATEST_RUN"
fi
